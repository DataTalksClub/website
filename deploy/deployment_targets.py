def role_profile_expectations(profile: str, target: DeploymentTarget) -> dict[str, str]:
    """Return the exact values ``profile`` must present for ``target``."""

    try:
        names = _ROLE_PROFILES[profile]["exact"]
    except KeyError as error:
        raise ReleaseContractError("unknown deployment role profile") from error
    return {name: _EXACT_EXPECTATIONS[name](target) for name in names}


def validate_environment(
    profile: str,
    values: Mapping[str, str],
    target: DeploymentTarget | None = None,
) -> None:
    """Fail closed when workflow variables select a different physical deployment."""

    resolved = SELECTED_TARGET if target is None else target
    expected = role_profile_expectations(profile, resolved)
    supplied = _ROLE_PROFILES[profile]["supplied"]

    missing = sorted(name for name in (*expected, *supplied) if not values.get(name))
    if missing:
        raise ReleaseContractError(
            f"{resolved.name} configuration is missing required values: " + ", ".join(missing)
        )
    mismatched = {
        name
        for name, expected_value in expected.items()
        if _normalize_json(name, values[name]) != _normalize_json(name, expected_value)
    }
    mismatched.update(
        name
        for name in supplied
        if resolved.identifier_disagreement(name, values.get(name)) is not None
    )
    if mismatched:
        raise ReleaseContractError(
            f"{resolved.name} configuration selects unexpected physical values: "
            + ", ".join(sorted(mismatched))
        )


def task_definition_arn_prefix(family: str) -> str:
    """Return the selected target's exact task-definition ARN prefix."""

    return SELECTED_TARGET.task_definition_arn_prefix(family)


def validate_release_record(payload: Any, target: DeploymentTarget | None = None) -> None:
    """Validate an immutable release record against one target's exact identifiers."""

    resolved = SELECTED_TARGET if target is None else target
    legacy_keys = {
        "image_digest",
        "migration_task_definition_arn",
        "rollback_eligible",
        "source_sha",
        "web_desired_count",
        "web_task_definition_arn",
        "worker_desired_count",
        "worker_task_definition_arn",
    }
    schema2_keys = legacy_keys | {"identity_schema", "version"}
    if not isinstance(payload, dict):
        raise ReleaseContractError("release record fields differ")
    payload_keys = frozenset(payload)
    if payload_keys not in {frozenset(legacy_keys), frozenset(schema2_keys)}:
        raise ReleaseContractError("release record fields differ")
    source_sha = payload["source_sha"]
    image_digest = payload["image_digest"]
    if not isinstance(source_sha, str) or re.fullmatch(r"[0-9a-f]{40}", source_sha) is None:
        raise ReleaseContractError("release record source SHA differs")
    if payload_keys == frozenset(schema2_keys):
        if payload["identity_schema"] != 2 or not isinstance(payload["version"], str):
            raise ReleaseContractError("release record identity schema differs")
        if re.fullmatch(
            r"[0-9]{8}-[0-9]{6}-[0-9a-f]{7}", payload["version"]
        ) is None or not payload["version"].endswith(f"-{source_sha[:7]}"):
            raise ReleaseContractError("release record version differs")
    if (
        not isinstance(image_digest, str)
        or re.fullmatch(r"sha256:[0-9a-f]{64}", image_digest) is None
        or image_digest
        in {
            "sha256:" + "0" * 64,
            "sha256:" + "1" * 64,
        }
    ):
        raise ReleaseContractError("release record image digest differs")
    family_fields = {
        "web_task_definition_arn": resolved.web_task_family,
        "worker_task_definition_arn": resolved.worker_task_family,
        "migration_task_definition_arn": resolved.migration_task_family,
    }
    for field_name, family in family_fields.items():
        value = payload[field_name]
        prefix = resolved.task_definition_arn_prefix(family)
        if (
            not isinstance(value, str)
            or re.fullmatch(re.escape(prefix) + r"[1-9][0-9]*", value) is None
        ):
            raise ReleaseContractError(f"release record {field_name} differs")
    if (
        payload["web_desired_count"] != resolved.web_desired_count
        or type(payload["web_desired_count"]) is not int
        or payload["worker_desired_count"] != resolved.worker_desired_count
        or type(payload["worker_desired_count"]) is not int
        or payload["rollback_eligible"] is not True
    ):
        raise ReleaseContractError("release record safety fields differ")


#: The architecture names a workflow may ask for, in ``GITHUB_OUTPUT`` order.
ARCHITECTURE_FIELDS: tuple[str, ...] = (
    "task_cpu_architecture",
    "build_platform",
    "image_architecture",
    "runner_machine",
    "runner_label",
)


def architecture_fields(target: DeploymentTarget | None = None) -> dict[str, str]:
    """Return the release image architecture names of one deployment target."""

    resolved = SELECTED_TARGET if target is None else target
    return {name: str(getattr(resolved, name)) for name in ARCHITECTURE_FIELDS}


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Validate deployment variables against the selected deployment target"
    )
    parser.add_argument("command", choices=[*ROLE_PROFILES, "architecture", "release-record"])
    parser.add_argument(
        "--field",
        choices=ARCHITECTURE_FIELDS,
        help=(
            "print one architecture value instead of every 'name=value' line "
            "(architecture command only)"
        ),
    )
    arguments = parser.parse_args()
    try:
        if arguments.command == "architecture":
            fields = architecture_fields()
            if arguments.field is not None:
                print(fields[arguments.field])
            else:
                for name, value in fields.items():
                    print(f"{name}={value}")
        elif arguments.command == "release-record":
            validate_release_record(json.load(sys.stdin))
        else:
            validate_environment(arguments.command, os.environ)
    except (json.JSONDecodeError, ReleaseContractError, DeploymentTargetError) as error:
        print(f"Deployment target validation failed safely: {error}", file=sys.stderr)
        raise SystemExit(1) from None


if __name__ == "__main__":
    main()
