class DeploymentTargetError(RuntimeError):
    """The configured deployment target is not a reviewed, deployable target."""


@dataclass(frozen=True, slots=True)
class CpuArchitecture:
    """One ``runtime_platform.cpu_architecture`` a Fargate task can declare.

    ECS does not reject a task definition whose image was built for the other
    architecture.  It starts the task, the kernel refuses the binary, and the
    task dies with nothing useful in its log, so the release pipeline has to
    build, assert and publish exactly the architecture the task definition
    declares.  Every name the pipeline needs for one architecture is derived
    here from that single Terraform value rather than repeated as a literal.
    """

    #: ``docker buildx build --platform`` value.
    build_platform: str
    #: ``docker image inspect --format '{{.Architecture}}'`` value.
    image_architecture: str
    #: ``platform.machine()`` of a host that runs this architecture natively.
    runner_machine: str
    #: GitHub-hosted runner label that executes this architecture natively.
    runner_label: str


#: The ``cpu_architecture`` values ``modules/django-website`` accepts.  Keep the
#: keys exactly the strings its ``validation`` block allows.
CPU_ARCHITECTURES: Mapping[str, CpuArchitecture] = {
    "ARM64": CpuArchitecture(
        build_platform="linux/arm64",
        image_architecture="arm64",
        runner_machine="aarch64",
        runner_label="ubuntu-24.04-arm",
    ),
    "X86_64": CpuArchitecture(
        build_platform="linux/amd64",
        image_architecture="amd64",
        runner_machine="x86_64",
        runner_label="ubuntu-latest",
    ),
}


@dataclass(frozen=True, slots=True)
class SuppliedIdentifier:
    """A physical value AWS generates, which arrives as a validated input."""

    name: str
    #: Where the owner obtains the value.  Recorded so an operator does not have
    #: to guess, and so a reviewer can tell an input apart from a reviewed pin.
    source: str
    #: ``str.format`` template evaluated against the target, giving a pattern
    #: scoped to that target's own account, region and namespace.
    pattern_template: str

    def pattern(self, target: DeploymentTarget) -> re.Pattern[str]:
        return re.compile(
            self.pattern_template.format(
                account=re.escape(target.aws_account_id),
                region=re.escape(target.aws_region),
                namespace=re.escape(target.resource_namespace),
            )
        )


SUPPLIED_IDENTIFIERS: tuple[SuppliedIdentifier, ...] = (
    SuppliedIdentifier(
        name="HOSTED_ZONE_ID",
        source="terraform output hosted_zone_id (Route 53 assigns it at zone creation)",
        pattern_template=r"Z[A-Z0-9]{{4,30}}",
    ),
    SuppliedIdentifier(
        name="KMS_KEY_ARN",
        source="terraform output kms_key_arn (KMS assigns the key id at creation)",
        pattern_template=(
            r"arn:aws:kms:{region}:{account}:key/"
            r"[0-9a-f]{{8}}-[0-9a-f]{{4}}-[0-9a-f]{{4}}-[0-9a-f]{{4}}-[0-9a-f]{{12}}"
        ),
    ),
    SuppliedIdentifier(
        name="ECS_SUBNET_IDS",
        source="terraform output task_subnet_ids (VPC assigns the subnet ids)",
        pattern_template=r'\["subnet-[0-9a-f]{{8,17}}"(?:,"subnet-[0-9a-f]{{8,17}}")*\]',
    ),
    SuppliedIdentifier(
        name="ECS_SECURITY_GROUP_IDS",
        source="terraform output task_security_group_ids (EC2 assigns the group ids)",
        pattern_template=r'\["sg-[0-9a-f]{{8,17}}"(?:,"sg-[0-9a-f]{{8,17}}")*\]',
    ),
    SuppliedIdentifier(
        name="WEB_TARGET_GROUP_ARN",
        source="terraform output web_target_group_arn (ELB assigns the ARN suffix)",
        pattern_template=(
            r"arn:aws:elasticloadbalancing:{region}:{account}:"
            r"targetgroup/{namespace}-web/[0-9a-f]{{16}}"
        ),
    ),
)
_SUPPLIED_BY_NAME = {identifier.name: identifier for identifier in SUPPLIED_IDENTIFIERS}


@dataclass(frozen=True, slots=True)
class DeploymentTarget:
    """One reviewed deployment target.

    Every field is a value a reviewer can read off the applied Terraform root,
    except :attr:`pinned_identifiers`, which records AWS-generated values that
    have already been reviewed for this target.
    """

    name: str
    aws_account_id: str
    aws_region: str
    hostname: str
    #: ``var.name`` of the ``modules/django-website`` instantiation.  Every ECS,
    #: ECR, IAM and Secrets Manager identifier below derives from it.
    resource_namespace: str
    settings_module: str
    dtc_environment: str
    #: The origin public canonical links point at.  A non-indexable staging or
    #: development host still declares the production apex (spec 02).
    canonical_origin: str
    #: Whether the deployed application marks every response ``noindex``.
    robots_noindex: bool
    github_environment: str
    terraform_root: str
    terraform_state_bucket: str
    #: ``task_cpu_architecture`` of this target's Terraform root, which
    #: ``modules/django-website`` puts in every task definition's
    #: ``runtime_platform``.  The release image is built for exactly this.
    task_cpu_architecture: str
    assign_public_ip: bool
    web_desired_count: int
    worker_desired_count: int
    resource_project_tag: str
    resource_environment_tag: str
    web_concurrency: str = "2"
    #: A retired target keeps its reviewed values so recorded evidence still
    #: resolves, but can never be selected for a deployment.
    retired: bool = False
    #: Reviewed exact values for AWS-generated identifiers, where a stack has
    #: already been applied and verified.  Anything absent here must be supplied
    #: at deploy time and is shape-validated instead.
    pinned_identifiers: Mapping[str, str] = field(default_factory=dict)

    def __post_init__(self) -> None:
        unknown = sorted(set(self.pinned_identifiers) - set(_SUPPLIED_BY_NAME))
        if unknown:
            raise DeploymentTargetError(
                f"{self.name} pins identifiers that are not supplied values: {', '.join(unknown)}"
            )
        if self.task_cpu_architecture not in CPU_ARCHITECTURES:
            raise DeploymentTargetError(
                f"{self.name} declares an unreviewed task CPU architecture: "
                f"{self.task_cpu_architecture!r}"
            )

    # -- release image architecture ----------------------------------------

    @property
    def cpu_architecture(self) -> CpuArchitecture:
        """The names derived from this target's declared task CPU architecture."""

        return CPU_ARCHITECTURES[self.task_cpu_architecture]

    @property
    def build_platform(self) -> str:
        return self.cpu_architecture.build_platform

    @property
    def image_architecture(self) -> str:
        return self.cpu_architecture.image_architecture

    @property
    def runner_machine(self) -> str:
        return self.cpu_architecture.runner_machine

    @property
    def runner_label(self) -> str:
        return self.cpu_architecture.runner_label

    # -- derived physical identifiers -------------------------------------

    @property
    def origin(self) -> str:
        return f"https://{self.hostname}"

    @property
    def terraform_state_key(self) -> str:
        return f"{self.terraform_root}/terraform.tfstate"

    @property
    def ecr_repository_name(self) -> str:
        return self.resource_namespace

    @property
    def ecr_repository_uri(self) -> str:
        return (
            f"{self.aws_account_id}.dkr.ecr.{self.aws_region}.amazonaws.com/"
            f"{self.ecr_repository_name}"
        )

    @property
    def ecs_cluster_arn(self) -> str:
        return (
            f"arn:aws:ecs:{self.aws_region}:{self.aws_account_id}:cluster/{self.resource_namespace}"
        )

    @property
    def web_service_name(self) -> str:
        return f"{self.resource_namespace}-web"

    @property
    def worker_service_name(self) -> str:
        return f"{self.resource_namespace}-worker"

    @property
    def web_task_family(self) -> str:
        return self.web_service_name

    @property
    def worker_task_family(self) -> str:
        return self.worker_service_name

    @property
    def migration_task_family(self) -> str:
        return f"{self.resource_namespace}-migration"

    @property
    def task_families(self) -> frozenset[str]:
        return frozenset(
            {self.web_task_family, self.worker_task_family, self.migration_task_family}
        )

    def _role_arn(self, suffix: str) -> str:
        return f"arn:aws:iam::{self.aws_account_id}:role/{self.resource_namespace}-{suffix}"

    @property
    def publisher_role_arn(self) -> str:
        return self._role_arn("github-publisher")

    @property
    def deployer_role_arn(self) -> str:
        return self._role_arn("github-deployer")

    @property
    def task_role_arn(self) -> str:
        return self._role_arn("task-application")

    @property
    def execution_role_arn(self) -> str:
        return self._role_arn("task-execution")

    def _secret_arn_pattern(self, container: str) -> re.Pattern[str]:
        return re.compile(
            rf"^arn:aws:secretsmanager:{re.escape(self.aws_region)}:{re.escape(self.aws_account_id)}"
            rf":secret:{re.escape(self.resource_namespace)}/{re.escape(container)}"
            rf"-[A-Za-z0-9]{{6}}$"
        )

    @property
    def database_secret_arn_pattern(self) -> re.Pattern[str]:
        return self._secret_arn_pattern("database-url")

    @property
    def django_secret_arn_pattern(self) -> re.Pattern[str]:
        return self._secret_arn_pattern("django-secret-key")

    def task_definition_arn_prefix(self, family: str) -> str:
        if family not in self.task_families:
            raise ReleaseContractError(f"task family is outside the {self.name} deployment target")
        return f"arn:aws:ecs:{self.aws_region}:{self.aws_account_id}:task-definition/{family}:"

    # -- runtime contract --------------------------------------------------

    @property
    def safety_environment(self) -> dict[str, str]:
        """Environment that keeps the adopted Datamailer client inert."""

        return {
            "DATAMAILER_SYNC_ON_USER_CREATE": "0",
            "DATAMAILER_OUTBOX_DISPATCH_IMMEDIATELY": "0",
            "DATAMAILER_TRANSACTIONAL_DRY_RUN": "1",
            "DATAMAILER_URL": "",
            "DATAMAILER_API_KEY": "",
        }

    @property
    def public_media_environment(self) -> dict[str, str]:
        """Where a deployed workload reads the public projection images from."""

        return {
            "PUBLIC_MEDIA_STORE_BACKEND": "s3",
            "PUBLIC_MEDIA_S3_BUCKET": "dtc-website-media",
            "PUBLIC_MEDIA_S3_REGION": self.aws_region,
        }

    @property
    def fixed_nonsecret_environment(self) -> dict[str, str]:
        """The exact non-secret container environment this target deploys."""

        return {
            "CANONICAL_ORIGIN": self.canonical_origin,
            "DJANGO_ALLOWED_HOSTS": self.hostname,
            "DJANGO_CSRF_TRUSTED_ORIGINS": self.origin,
            "DJANGO_SETTINGS_MODULE": self.settings_module,
            "DTC_ENVIRONMENT": self.dtc_environment,
            "OBSERVABILITY_EVENT_BACKENDS": "log",
            "WEB_CONCURRENCY": self.web_concurrency,
            "AWS_DEFAULT_REGION": self.aws_region,
            "AWS_REGION": self.aws_region,
            **self.public_media_environment,
            **self.safety_environment,
        }

    # -- supplied identifiers ---------------------------------------------

    def identifier_disagreement(self, name: str, value: str | None) -> str | None:
        """Return a reason when ``value`` is not this target's identifier."""

        identifier = _SUPPLIED_BY_NAME.get(name)
        if identifier is None:
            raise DeploymentTargetError(f"{name} is not a supplied deployment identifier")
        if not value:
            return "is missing"
        pinned = self.pinned_identifiers.get(name)
        normalized = _normalize_json(name, value)
        if pinned is not None:
            if normalized != _normalize_json(name, pinned):
                return "differs from the reviewed value"
            return None
        if identifier.pattern(self).fullmatch(normalized) is None:
            return f"is not a {self.name} {name.lower().replace('_', ' ')}"
        # A subnet, security-group or hosted-zone id carries no account, so its
        # shape alone cannot tell one deployment's from another's.  Any value
        # another reviewed target pinned is therefore rejected by name, and the
        # remaining protection is that the deployer role can only act inside its
        # own account.
        for other in DEPLOYMENT_TARGETS.values():
            if other.name == self.name:
                continue
            reviewed = other.pinned_identifiers.get(name)
            if reviewed is not None and _normalize_json(name, reviewed) == normalized:
                return f"belongs to the {other.name} deployment target"
        return None


def _normalize_json(name: str, value: str) -> str:
    if name not in _JSON_LIST_VALUES:
        return value
    try:
        return json.dumps(json.loads(value), separators=(",", ":"), sort_keys=True)
    except json.JSONDecodeError as error:
        raise ReleaseContractError(f"deployment variable {name} is not valid JSON") from error


