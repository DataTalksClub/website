"""Reviewed deployment targets for the release pipeline.

A deployment target is a *named, reviewed profile* of one applied website stack:
its account and region, the hostname it serves, the physical resource namespace
its ECS/ECR/IAM identifiers derive from, the Django settings module and
``DTC_ENVIRONMENT`` its tasks run with, and its desired counts.  Every gate in
``deploy/`` reads its expectations from the selected target instead of pinning
one deployment's strings, so moving the pipeline to another reviewed stack is a
configuration change rather than an edit spread across the release tooling.

The selection stays closed, following the precedent set by
``deploy.development_target``:

* the allowlist lives in code (:data:`DEPLOYMENT_TARGETS`);
* ``DTC_DEPLOYMENT_TARGET`` only *selects* a member of that allowlist, so a
  mistyped or injected value fails at import rather than widening the boundary;
* a retired target can still be read for historical evidence but can never be
  selected for a deployment; and
* every expectation a target publishes is still compared exactly, so a stack
  that disagrees with its own reviewed profile fails closed with the name of the
  value that disagreed.

Some identifiers are generated by AWS and cannot be known before the stack is
applied -- the KMS key ARN, the hosted zone id, subnet and security-group ids,
and the load-balancer target-group ARN.  They are never invented here.  A target
either *pins* the reviewed value it was verified against (the historical sandbox
does) or declares the strict shape the supplied value must have
(:data:`SUPPLIED_IDENTIFIERS`), scoped to that target's own account, region and
namespace.  Supplying another deployment's subnet or a wrong-account key ARN is
therefore still rejected.
"""

