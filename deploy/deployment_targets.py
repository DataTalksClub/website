def registered_target(name: str) -> DeploymentTarget:
    """Return a reviewed target by name, including retired ones."""

    try:
        return DEPLOYMENT_TARGETS[name]
    except KeyError:
        raise DeploymentTargetError(f"{name!r} is not a reviewed deployment target") from None


def deployment_target(environ: Mapping[str, str] | None = None) -> DeploymentTarget:
    """Return the selected deployment target, failing closed on anything else."""

    values = os.environ if environ is None else environ
    name = values.get(DEPLOYMENT_TARGET_VARIABLE) or DEFAULT_DEPLOYMENT_TARGET
    target = registered_target(name)
    if target.retired:
        raise DeploymentTargetError(f"deployment target {name!r} is retired and cannot be deployed")
    return target


